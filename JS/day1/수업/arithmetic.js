// 연산 (operation)

// 산술 연산자 
// 결과 :  

let a = 10;
let b = 3;

// console.log(a + b)
// console.log(a - b)
console.log(a * b)
console.log(a / b)  // 나누기

// 몫 연산(3)
// 파이썬에서는 a // b 하면 몫이 나옴
// 자바스크립트에서는 주석이 됨 (몫 연산 따로 없음)
console.log(Math.floor(a / b))          // a를 b로 나누고 정수부분만 (앞부분만) 

// 나머지 연산(1)
// 파이썬에서는 a % b 하면 나머지가 나옴
console.log(a % b)